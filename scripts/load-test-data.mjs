#!/usr/bin/env node

const baseUrl = (process.env.LOGARYS_CONSOLE_API_URL ?? "http://localhost:3002").replace(/\/$/, "");
const pipelineName = process.env.LOGARYS_TEST_PIPELINE_NAME ?? "logarys-test-pipeline";
const logCount = Number.parseInt(process.env.LOGARYS_TEST_LOG_COUNT ?? "100", 10);

async function request(path, body) {
  const response = await fetch(`${baseUrl}${path}`, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Accept: "application/json"
    },
    body: JSON.stringify(body)
  });

  const text = await response.text();
  let data = text;
  try {
    data = text ? JSON.parse(text) : null;
  } catch {}

  if (!response.ok) {
    throw new Error(`${response.status} ${response.statusText}: ${text}`);
  }

  return data;
}

const payload = {
  pipelineName,
  logCount,
  pipeline: {
    id: pipelineName,
    name: pipelineName,
    enabled: true,
    inputType: "http",
    description: "Test pipeline generated by scripts/load-test-data.mjs"
  }
};

try {
  console.log(`Loading test data through console-manager: ${baseUrl}`);
  const result = await request("/test-data", payload);
  console.log(JSON.stringify(result, null, 2));
  console.log("Done.");
} catch (error) {
  console.error("Unable to load test data through console-manager.");
  console.error(error instanceof Error ? error.message : error);
  console.error("Make sure console-manager has LOGARYS_ENABLE_TEST_DATA_ENDPOINTS=true in local/dev only.");
  process.exitCode = 1;
}
